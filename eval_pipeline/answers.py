"""Run the agent on the ten included evaluation questions.

Answers are generated by the agent without reading the public answer key.
"""

from __future__ import annotations

import argparse
import json
import os
import time
import shutil
from datetime import datetime, timezone
from pathlib import Path
from typing import Callable
from uuid import uuid4

from openai import APIError

from src.ingestion_pipeline import ROOT
from .generation_metrics import measured_metrics


def _write_json(path: Path, value: object) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(path.name + ".tmp")
    temporary.write_text(json.dumps(value, indent=2, ensure_ascii=False) + "\n")
    temporary.replace(path)


def _source_modalities(sources: list[dict]) -> list[str]:
    modalities = set()
    for source in sources:
        kind = str(source.get("kind") or source.get("type") or "").lower()
        if kind in {"sql", "sqlite", "database"} or source.get("sql") or source.get("query"):
            modalities.add("sql")
        if kind in {"pdf", "filing", "document"} or source.get("filename"):
            modalities.add("pdf")
    return sorted(modalities)


def _generate_record(item: dict, answerer: Callable[[str], dict], model: str | None) -> dict:
    """Run one question and keep the answer, review state, or failure inspectable."""
    started = time.monotonic()
    try:
        response = answerer(item["question"])
        if not isinstance(response, dict) or not isinstance(response.get("answer"), str):
            raise ValueError("Agent did not return an answer string")
        answer = response["answer"].strip()
        if not answer:
            raise ValueError("Agent returned an empty answer")
        sources = response.get("sources", [])
        if not isinstance(sources, list):
            raise ValueError("Agent sources must be a list")
        modalities = _source_modalities(sources)
        record = {"id": item["id"], "question": item["question"], "answer": answer,
                  "model": response.get("model", model),
                  "answer_status": response.get("answer_status", "answered"),
                  "model_diagnostics": response.get("model_diagnostics", []),
                  "verification": response.get("verification"),
                  "failure_reason": response.get("failure_reason"),
                  "draft": response.get("draft") if response.get("draft") != answer else None,
                  "sources": sources, "trace": response.get("trace", []),
                  "required_modalities": item["required_modalities"],
                  "source_modalities": modalities,
                  "source_coverage": all(modality in modalities for modality in item["required_modalities"]),
                  "error": None}
    except APIError as exc:
        raise RuntimeError("Fireworks request failed; check network access and the API key. "
                           "Completed answers from this run remain saved.") from exc
    except Exception as exc:
        record = {"id": item["id"], "question": item["question"],
                  "required_modalities": item["required_modalities"],
                  "error": f"{type(exc).__name__}: {exc}"}
    record["elapsed_seconds"] = round(time.monotonic() - started, 2)
    record["metrics"] = measured_metrics(record)
    return record


def _archive_legacy_run(root: Path) -> None:
    """Preserve a pre-history full run before the active files are replaced."""
    active = root / "evaluation/dev_run.json"
    if not active.is_file():
        return
    try:
        old = json.loads(active.read_text())
    except (OSError, ValueError):
        return
    old_id = old.get("run_id")
    if isinstance(old_id, str) and (root / "evaluation/runs" / old_id / "dev_run.json").is_file():
        return
    old_id = "legacy-" + datetime.fromtimestamp(active.stat().st_mtime, timezone.utc).strftime("%Y%m%d-%H%M%S")
    folder = root / "evaluation/runs" / old_id
    if folder.exists():
        for saved in (root / "evaluation/runs").glob(old_id + "*/dev_run.json"):
            if saved.read_bytes() == active.read_bytes():
                return
        folder = root / "evaluation/runs" / (old_id + "-" + uuid4().hex[:6])
    folder.mkdir(parents=True)
    shutil.copy2(active, folder / "dev_run.json")
    answers = root / "dev_answers.json"
    if answers.is_file():
        shutil.copy2(answers, folder / "dev_answers.json")


def run_development(answerer: Callable[[str], dict], *, root: Path = ROOT,
                    ids: set[str] | None = None, output_dir: Path | None = None,
                    progress: Callable[[int, int, str], None] | None = None,
                    model: str | None = None,
                    preserve_previous: bool = False) -> dict:
    """Save generated answers and inspectable per-question evidence records."""
    questions = json.loads((root / "questions/dev_questions.json").read_text())
    unknown = (ids or set()) - {item["id"] for item in questions}
    if unknown:
        raise ValueError(f"Unknown development question IDs: {', '.join(sorted(unknown))}")
    selected = [item for item in questions if ids is None or item["id"] in ids]
    if not selected:
        raise ValueError("Select at least one development question")
    destination = Path(output_dir or root / "evaluation")
    answers_path = (root / "dev_answers.json" if ids is None and output_dir is None else
                    destination / ("dev_answers.json" if ids is None else "partial_dev_answers.json"))
    records_path = destination / ("dev_run.json" if ids is None else "partial_dev_run.json")
    if ids is None and output_dir is None:
        _archive_legacy_run(root)
        if preserve_previous and (root / "dev_answers.json").is_file():
            shutil.copy2(root / "dev_answers.json", root / "previous_answers.json")
    run_id = "run-" + datetime.now(timezone.utc).strftime("%Y%m%d-%H%M%S") + "-" + uuid4().hex[:6]
    run_folder = root / "evaluation/runs" / run_id if output_dir is None else destination / "runs" / run_id
    started_at = datetime.now(timezone.utc).isoformat(timespec="seconds")
    records = []
    answers = {}
    for item in selected:
        record = _generate_record(item, answerer, model)
        records.append(record)
        if record.get("answer"):
            answers[item["id"]] = record["answer"]
        _write_json(answers_path, answers)
        run = {"run_id": run_id, "started_at": started_at, "model": model,
               "total": len(selected), "questions": records}
        _write_json(records_path, run)
        _write_json(run_folder / "dev_run.json", run)
        _write_json(run_folder / "dev_answers.json", answers)
        if progress:
            progress(len(records), len(selected), item["id"])
    return {"answers_path": str(answers_path), "records_path": str(records_path),
            "completed": len(answers), "total": len(selected),
            "source_coverage_count": sum(bool(row.get("source_coverage")) for row in records)}


def retry_answer(question_id: str, answerer: Callable[[str], dict], *, root: Path = ROOT,
                 model: str | None = None) -> dict:
    """Replace one saved answer and snapshot a new full run; preserve the prior run."""
    questions = json.loads((root / "questions/dev_questions.json").read_text())
    item = next((row for row in questions if row["id"] == question_id), None)
    if item is None:
        raise ValueError("Choose a development question")
    path = root / "evaluation/dev_run.json"
    run = json.loads(path.read_text())
    records = run.get("questions", [])
    index = next((index for index, row in enumerate(records) if row["id"] == question_id), None)
    if index is None or len(records) != len(questions):
        raise ValueError("Generate all ten answers before retrying one")
    record = _generate_record(item, answerer, model)
    if record.get("error"):
        return {"updated": False, "record": record}
    _archive_legacy_run(root)
    updated = records.copy()
    updated[index] = record
    run_id = "run-" + datetime.now(timezone.utc).strftime("%Y%m%d-%H%M%S") + "-" + uuid4().hex[:6]
    new_run = {**run, "run_id": run_id, "questions": updated,
               "retried_question_id": question_id}
    answers = {row["id"]: row["answer"] for row in updated if row.get("answer")}
    folder = root / "evaluation/runs" / run_id
    _write_json(folder / "dev_run.json", new_run)
    _write_json(folder / "dev_answers.json", answers)
    _write_json(path, new_run)
    _write_json(root / "dev_answers.json", answers)
    return {"updated": True, "run_id": run_id, "record": record}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--ids", nargs="+", help="Run only these development question IDs")
    parser.add_argument("--output-dir", type=Path)
    args = parser.parse_args()
    from src.answer_agent.graph import answer_question
    from src.config import load_local_fireworks_key

    load_local_fireworks_key()
    if not os.getenv("FIREWORKS_API_KEY"):
        parser.error("Set FIREWORKS_API_KEY in .env or the environment before running evaluation")

    try:
        result = run_development(answer_question, ids=set(args.ids) if args.ids else None,
                                 output_dir=args.output_dir)
    except RuntimeError as exc:
        parser.exit(1, f"Evaluation stopped: {exc}\n")
    print(json.dumps(result, indent=2))


if __name__ == "__main__":
    main()
